def compute_gradients(X, y, w):
    gradients = np.zeros_like(w)
    y_pred = predict(X, w)

    n  = len(X)
    for i in range(n):
      error = y_pred[i] - y[i] #errors calc for each prediction
      for j in range(len(w)):
          gradients[j] += 2 * (error * X[i][j]) / n #gradients formula

    return gradients

def gradient_descent_step(w, grads, lr):
  for j in range(len(w)):
        w[j] = w[j] - lr * grads[j] #weight adjustment

  return w

