"""Task 2: Hypothesis and Loss"""

#predicts value for only 1 sample
def predict_single(x, w):
    y_hat = 0

    for i in range(len(w)):
        y_hat += w[i] * x[i]

    return y_hat

#for whole dataset
def predict(X, w):
    predictions = []

    for i in range(len(X)):
        pred = predict_single(X[i], w)
        predictions.append(pred)

    return np.array(predictions)

def mse_loss(X, y, w):
    y_pred = predict(X, w)
    mse = np.mean((y - y_pred) ** 2)
    return mse

