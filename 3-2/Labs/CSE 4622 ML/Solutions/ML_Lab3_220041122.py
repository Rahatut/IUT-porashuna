"""Task 4: Gradient Descent — With Regularization"""

def mse_loss_l2(X, y, w, lamda):
    y_pred = predict(X, w)
    val1   = np.mean((y - y_pred) ** 2)
    val2   = lamda * np.sum(w[1:] ** 2)   # skip bias (index 0)
    return val1 + val2

def mse_loss_l1(X, y, w, lamda):
    y_pred = predict(X, w)
    val1   = np.mean((y - y_pred) ** 2)
    val2   = lamda * np.sum(np.abs(w[1:]))  # skip bias (index 0)
    return val1 + val2

def compute_gradients_l2(X, y, w, lamda):
    gradients = np.zeros_like(w)
    y_pred    = predict(X, w)
    n         = len(X)

    for i in range(n):
        error = y_pred[i] - y[i]
        for j in range(len(w)):
            gradients[j] += (2 * error * X[i][j]) / n

    for j in range(1, len(w)):
        gradients[j] += 2 * lamda * w[j] / n

    return gradients

def sign(x):
    if x > 0:
        return 1
    elif x < 0:
        return -1
    else:
        return 0

def compute_gradients_l1(X, y, w, lamda):
  gradients = np.zeros_like(w)
  y_pred    = predict(X, w)
  n         = len(X)

  for i in range(n):
    error = y_pred[i] - y[i]
    for j in range(len(w)):
      gradients[j] += (2 * error * X[i][j]) / n

  for j in range(1, len(w)):
    gradients[j] += lamda * sign(w[j])/ n

  return gradients

